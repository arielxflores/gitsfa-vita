#!/usr/bin/env python3
# names_gen.h for the skills host test: the FMOD event names of engine/src/audio.h (EV_DEF) and the RAM-sound / voice-line
# names of build/data/audio_manifest.txt. Usage: gen_names.py audio.h audio_manifest.txt out.h
import re, sys
src, man, out = sys.argv[1:4]
txt = open(src).read()
m = re.search(r'static const EvDef EV_DEF\[\d+\] = \{(.*?)\n\};', txt, re.S)
ev = sorted(set(re.findall(r'\{"([^"]+)",\d+,', m.group(1)))) if m else []
if not m:   # databuilder: the table is data now (events.gev beside the manifest, engine/src/ev_table.h)
    import os, struct
    g = os.path.join(os.path.dirname(os.path.abspath(man)), 'events.gev')
    if os.path.exists(g):
        d = open(g, 'rb').read(); nc, nl, ne, nm, nx, nt, sb = struct.unpack_from('<7I', d, 4); so = 32 + ((nc * 17 + 3) & ~3)
        S = d[so:so + sb]; eo = so + sb + 40 * nl
        ev = sorted(set(S[q:S.index(b'\0', q)].decode('latin1') for q in (struct.unpack_from('<I', d, eo + 40 * i)[0] for i in range(ne))))
ram, voice = [], []
for ln in open(man):
    f = ln.split()
    if len(f) < 2 or ln.startswith('#'): continue
    if f[1] == 'ram': ram.append(f[0])
    elif f[1] == 'voice': voice.append(f[0])
with open(out, 'w') as o:
    o.write('// generated by gen_names.py: name checks for the audio stub\n')
    for name, lst in (('TEST_EV', ev), ('TEST_RAM', sorted(ram)), ('TEST_VOICE', sorted(voice))):
        o.write('static const char *const %s[] = {\n' % name + ''.join('\t"%s",\n' % n for n in lst) + '};\n')
print('names: %d events, %d RAM sounds, %d voice lines' % (len(ev), len(ram), len(voice)))
